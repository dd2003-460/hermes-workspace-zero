"""
================================================================================
【注释学习版】m_BH_m_ZAMS.py —— 前身星质量 → 黑洞质量 的映射公式
================================================================================
原始文件：raw/老师源码_Millennium并合率2017/m_BH_m_ZAMS.py（原样未改，本文件只加注释）

这个文件是老师代码里**物理含量最高、和我们项目关系最直接**的一个：
它实现的就是 Spera, Mapelli & Bressan 2015（我们仓库 literature/raw/1505.05281.pdf，
即 raw/1505.05201.pdf）**附录 C 的拟合公式**——我们项目 2.2 遗迹质量引擎
（2_Stellar_Mass_BH_Engine/2.2_Remnant_Mass_Recipes）逐行复现的正是这一套。

直白说它干什么：
    输入：一颗恒星诞生时的质量 M_ZAMS（零龄主序质量，单位 M☉）+ 它出生环境的
          金属丰度 Z（质量分数，太阳是 0.02 左右）；
    输出：这颗恒星死后留下的致密遗迹质量 M_rem（黑洞或中子星，单位 M☉）。

为什么金属丰度重要（你的理解链的"金属丰度影响爆发时被吹飞的质量"）：
    金属越少 → 恒星演化时的星风越弱 → 外层物质吹飞得越少 → 留下的黑洞越重。
    代码里所有分段（Z > 4e-3 / 1e-3~4e-3 / < 1e-3）和 f(M_CO,Z) 函数都是在编码这件事。

================================================================================
"""

import numpy as np


def compute_M_rem(M_ZAMS, Z):
    """
    根据附录C中的公式计算最终致密残留物质量 M_rem

    参数：
    M_ZAMS : float
        零龄主序质量（以太阳质量为单位）
    Z : float
        金属丰度

    返回：
    float
        致密残留物质量 M_rem（以太阳质量为单位）
    """

    # 1. 首先计算 M_CO 作为 M_ZAMS 和 Z 的函数
    def compute_M_CO(M_ZAMS, Z):
        # ---- g(x, y, delta)：一条平滑的"逻辑斯蒂"开关函数 ------------------
        # 物理作用：把 M_CO 随 M_ZAMS 的变化做成"先平台、再陡升、再平台"的三段式。
        # g ≈ 0.5 时 M_ZAMS = x（转折点），delta 越大过渡越陡。
        # 写成 0.5/(1+10^((x-M_ZAMS)*delta))：M_ZAMS 远小于 x 时 g≈1，远大于 x 时 g≈0。
        def g(x, y, delta):
            return 0.5 / (1 + 10**((x - M_ZAMS) * delta))

        # ---- 分三个金属丰度段给系数（Spera 附录 C 的 C1–C10 拟合）---------
        # 这些 B1/K1/K2/delta 全部是对 SEVN 模拟结果的多项式拟合，不是解析推导。
        # Z 单位是质量分数（0.02 = 太阳；0.002 = 1/10 太阳；0.0002 = 1/100 太阳）。
        if Z > 4.0e-3:  # 高金属丰度段（≈ Z > 0.2 Z☉）
            B1 = 59.63 - 2.969e3 * Z + 4.988e4 * Z**2
            K1 = 45.04 - 2.176e3 * Z + 3.806e4 * Z**2
            K2 = 1.389e2 - 4.664e3 * Z + 5.106e4 * Z**2
            delta1 = 2.790e-2 - 1.780e-2 * Z + 77.05 * Z**2
            delta2 = 6.730e-3 + 2.690 * Z - 52.39 * Z**2
        elif 1.0e-3 <= Z <= 4.0e-3:  # 中金属丰度段
            B1 = 40.98 + 3.415e4 * Z - 8.064e6 * Z**2
            K1 = 35.17 + 1.548e4 * Z - 3.759e6 * Z**2
            K2 = 20.36 + 1.162e5 * Z - 2.276e7 * Z**2
            delta1 = 2.500e-2 - 4.346 * Z + 1.340e3 * Z**2
            delta2 = 1.750e-2 + 11.39 * Z - 2.902e3 * Z**2
        else:  # Z < 1.0e-3，低金属丰度段（≈ Z < 0.05 Z☉，近 Pop III 环境）
            B1 = 67.07
            K1 = 46.89
            K2 = 1.138e2
            delta1 = 2.199e-2
            delta2 = 2.602e-2

        # ---- M_CO：碳氧核质量（CO core mass）------------------------------
        # 物理意义：恒星演化到最后，外层吹走后剩下的碳氧核有多重。
        # 它由两段逻辑斯蒂相加再线性缩放得到：
        #   g1 控制"低质量端开始产生 CO 核"的转折（K1 附近），
        #   g2 控制"高质量端 CO 核增长饱和"的转折（K2 附近）。
        # B1 是高质量端的平台值（CO 核质量上限，随 Z 变化——Z 越低平台越高，
        # 这就是"金属少→吹飞少"在 CO 核上的第一层体现）。
        g1 = g(K1, delta1, delta1)
        g2 = g(K2, delta2, delta2)
        M_CO = -2.0 + (B1 + 2.0) * (g1 + g2)
        return M_CO

    # 2. 计算 M_rem
    M_CO = compute_M_CO(M_ZAMS, Z)

    # ---- 遗迹质量同样分两个大段 -------------------------------------------
    if Z <= 5.0e-4:
        # ===== 公式 C1-C3：极低金属丰度（Z ≤ 0.025 Z☉）=====
        # p(M_CO)：一个二次多项式，把 CO 核质量映射成遗迹质量
        def p(M_CO):
            return -2.333 + 0.1559 * M_CO + 0.2700 * M_CO**2

        # f(M_CO, Z)：低 Z 段的"回落"机制——M_CO 太大时直接回落：
        # 对不稳定对超新星（PISN）把整个恒星炸飞，不留下黑洞，
        # 质量落在 60–133 M☉ 氦核窗口的前身星会被完全摧毁（这就是"质量间隙"）。
        def f(M_CO, Z):
            m = -6.476e2 * Z + 1.911   # 斜率：Z 越小斜率越大（低金属回落越狠）
            q = 2.300e3 * Z + 11.67    # 截距
            return m * M_CO + q

        # 三段判据：小 CO 核取 max(p, 1.27)（1.27 是中子星下限，防算式给出负质量）；
        # 中间段直接用 p；大 CO 核取 min(p, f)——回落生效，模拟 PISN 吹飞。
        if M_CO <= 5.0:
            M_rem = max(p(M_CO), 1.27)
        elif 5.0 < M_CO < 10.0:
            M_rem = p(M_CO)
        else:  # M_CO >= 10.0
            M_rem = min(p(M_CO), f(M_CO, Z))

    else:  # Z > 5e-4
        # ===== 公式 C4-C10：中高金属丰度 =====
        # h(M_CO, Z)：一条 S 型曲线（逻辑斯蒂），替代低 Z 段的二次多项式。
        # 直白说：M_CO 小时 h 给低值，M_CO 大时 h 饱和到 A2 平台——
        # A2 就是该金属丰度下"直接坍缩"能留下的最重黑洞。
        def h(M_CO, Z):
            if Z >= 1.0e-3:  # 中高 Z：用有理式拟合 A1/A2/L/eta 四个参数
                A1 = 1.340 - 29.46 / (1 + (Z / 1.110e-3)**2.361)   # 低端平台
                A2 = 80.22 - 74.73 * (Z**0.965) / (2.720e-3 + Z**0.965)  # 高端平台（随 Z 下降！）
                L = 5.683 + 3.533 / (1 + (Z / 7.430e-3)**1.993)    # 转折点位置
                eta = 1.066 - 1.121 / (1 + (Z / 2.558e-2)**0.609)  # 过渡陡度
            else:  # 5e-4 < Z < 1e-3：过渡段，系数用线性/二次拟合
                A1 = 1.105e5 * Z - 1.258e2
                A2 = 91.56 - 1.957e4 * Z - 1.558e7 * Z**2
                L = 1.134e4 * Z - 2.143
                eta = 3.090e-2 - 22.30 * Z + 7.363e4 * Z**2
            return A1 + (A2 - A1) / (1 + 10**((L - M_CO) * eta))

        # f(M_CO, Z)：同上，回落机制（PISN 质量间隙），斜率按 Z 分段
        def f(M_CO, Z):
            if Z >= 2.0e-3:
                m = 1.217
                q = 1.061
            elif 1.0e-3 <= Z < 2.0e-3:
                m = -43.82 * Z + 1.304
                q = -1.296e4 * Z + 26.98
            else:  # 5.0e-4 < Z < 1.0e-3
                m = -6.476e2 * Z + 1.911
                q = 2.300e3 * Z + 11.67
            return m * M_CO + q

        # 注意这里和低 Z 段的关键区别：
        #   大 CO 核时取 **max**(h, f) 而不是 min(p, f)——
        #   中高 Z 下 PISN 窗口的前身星质量更高，回落线与 h 的相对位置翻转。
        if M_CO <= 5.0:
            M_rem = max(h(M_CO, Z), 1.27)
        elif 5.0 < M_CO < 10.0:
            M_rem = h(M_CO, Z)
        else:  # M_CO >= 10.0
            M_rem = max(h(M_CO, Z), f(M_CO, Z))

    return M_rem


# 示例使用
if __name__ == "__main__":
    # 测试不同参数
    test_cases = [
        (20.0, 0.02),  # M_ZAMS=20太阳质量, Z=0.02（太阳金属丰度）
        (30.0, 0.002), # M_ZAMS=30太阳质量, Z=0.002（1/10 太阳）
        (50.0, 0.0002),# M_ZAMS=50太阳质量, Z=0.0002（1/100 太阳）
        (100.0, 0.0001)# M_ZAMS=100太阳质量, Z=0.0001
    ]

    for M_ZAMS, Z in test_cases:
        M_rem = compute_M_rem(M_ZAMS, Z)
        print(f"M_ZAMS={M_ZAMS} M☉, Z={Z:.4f} => M_rem={M_rem:.2f} M☉")


